def _col(ps, p):
    i = 0
    while i < len(ps):
        if abs(ps[i] - p) < 1e-9:
            return i
        i += 1
    return -1

def _row(vs, v):
    # exact df, else the next smaller tabulated df (conservative); 0 = infinity
    best = -1
    i = 0
    while i < len(vs):
        if vs[i] == v:
            return i
        if vs[i] != 0 and vs[i] < v:
            best = i
        i += 1
    if v > 200:
        return len(vs) - 1
    return best

def z_crit(p):
    # upper-tail probability p -> z
    c = _col(_ZP, p)
    return None if c < 0 else _Z[c]

def t_crit(df, p):
    # upper-tail probability p (0.1, 0.05, 0.025, 0.01, 0.005) with df degrees of freedom
    c = _col(_TP, p)
    r = _row(_TV, df)
    if c < 0 or r < 0:
        return None
    return _T[r][c]

def chi_crit(df, p):
    # upper-tail p in (0.1, 0.05, 0.025, 0.01, 0.005) or lower tail via p = 0.9 .. 0.995
    c = _col(_CP, p)
    r = _row(_CV, df)
    if c < 0 or r < 0 or df > 100:
        return None
    return _C[r][c]

def pmcc_crit(n, p):
    # one-tail p in (0.05, 0.025, 0.01, 0.005); n = 4 .. 30
    c = _col(_RP, p)
    if c < 0 or n < 4 or n > 30:
        return None
    return _R[n - 4][c]

# Spearman's rs, exact: largest D with P(sum d^2 <= D) <= p under H0,
# one-tail p = 5%, 2.5%, 1%, 0.5%, n = 4 .. 20 (-1: no D is small enough).
# Counted over all n! rank orders by a DP (not typed from a book); the
# critical rs is 1 - 6D/(n^3 - n).
