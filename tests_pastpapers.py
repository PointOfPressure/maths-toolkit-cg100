TOOLS = {}

def _tool(modname, label):
    # modname may carry a section code: 'mpure:B'
    key = modname + '/' + label
    if key not in TOOLS:
        TOOLS[key] = None
        code = None
        if ':' in modname:
            modname, code = modname.split(':')
        for c, title, tools in __import__(modname).SECTIONS:
            if code is not None and c != code:
                continue
            for lab, spec, fn in tools:
                if lab == label and TOOLS[key] is None:
                    TOOLS[key] = (spec, fn)
    return TOOLS[key]

def _flat(lines):
    out = []
    for ln in lines or []:
        if isinstance(ln, tuple):
            if ln[0] in ('m', 'mw'):
                out.append(caseng.tostr(ln[1]))
            else:
                out.append(str(ln[1]))
        else:
            out.append(str(ln))
    return '\n'.join(out)

def output(module, label, inputs, ask=None, deg=False, full=False):
    # CAS inputs may carry the follow-up answer as 'f(x) ; ask'
    casutil.DEG = deg
    casutil.FULL = full
    try:
        return _output(module, label, inputs, ask)
    finally:
        casutil.DEG = False
        casutil.FULL = False

def _output(module, label, inputs, ask):
    if module in ('CALC', 'casui:Calculate'):
        casui.ANS[0] = ('n', 0)
        try:
            return _flat(casui._forms(inputs))
        except Exception as e:
            return 'error: ' + repr(e)
    if module in ('CAS', 'casui:CAS'):
        parts = inputs.split(' ; ')
        expr = parts[0]
        if len(parts) > 1:
            ask = parts[1]
        old = casutil.ask
        casutil.ask = lambda spec, lab='': None if ask is None else casutil.convert(spec, ask)
        try:
            s, tree = casui._parse_eq(expr)
            lines = casui._cas_op(casui.CAS_OPS.index(label), tree, s)
        except Exception as e:
            lines = [('!', 'error: ' + repr(e))]
        casutil.ask = old
        return _flat(lines)
    t = _tool(module, label)
    if t is None:
        return 'no such tool'
    try:
        vals = casutil.convert(t[0], inputs)
    except ValueError as e:
        return 'parse error: ' + str(e)
    return _flat(casutil.call_tool(t[1], vals))

