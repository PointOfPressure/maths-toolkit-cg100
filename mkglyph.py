# space after the ink; symbols that sit between terms get more room
GAP = {'<': 3, '>': 3, '#': 3, '~': 3, '-': 3, '=': 3, '%': 3, '+': 3, 'x': 3, 'U': 3, 'N': 3, 'E': 3,
       'Z': 3, 'I': 2}


def _pix(asc, rows):
    out = []
    for y in range(len(rows)):
        for x in range(len(rows[y])):
            if rows[y][x] == '#':
                out.append(x + 1)
                out.append(y - asc + 32)
    return bytes(out)


def table(art):
    t = {}
    for code in sorted(art):
        asc, rows = art[code]
        w = max(len(r.rstrip('.')) for r in rows)
        adv = w + 1 + GAP.get(code, 2)
        t[code] = (adv, asc, len(rows) - asc, _pix(asc, rows))
    return t


def source():
    out = ['# Generated by mkglyph.py: pixel glyphs for Greek letters and maths symbols.',
           '# code -> (advance, ascent, descent, x / y+32 pixel pairs from the baseline)']
    for name, art in (('M', MEDIUM), ('S', SMALL)):
        out.append(name + ' = {')
        t = table(art)
        for code in sorted(t):
            adv, asc, desc, pix = t[code]
            out.append('    %r: (%d, %d, %d, %r),' % (code, adv, asc, desc, pix))
        out.append('}')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    assert sorted(MEDIUM) == sorted(SMALL)
    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, 'texg.py'), 'w').write(source())
    print('wrote texg.py: %d glyphs a size' % len(MEDIUM))
